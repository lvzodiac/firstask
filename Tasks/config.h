#ifndef CONFIG_H
#define CONFIG_H

// ============================================================================
//  工程配置：所有可调参数集中在此，便于统一调试与阅读
// ============================================================================

// ----------------------------------------------------------------------------
// 独立看门狗 IWDG
//   CubeMX 中默认开启（见 Core/Src/iwdg.c / C_project.ioc）：
//     预分频 IWDG_PRESCALER_64, 重装载值 400
//     LSI 约 32kHz 时，超时时间约为 64 * (400 + 1) / 32000 = 0.802s。
//   1 = 正常喂狗；0 = 停止喂狗，不会关闭已启动的 IWDG，会导致超时复位。
// ----------------------------------------------------------------------------
#define WATCHDOG_ENABLE           1

// ----------------------------------------------------------------------------
// 控制周期
// ----------------------------------------------------------------------------
#define CONTROL_FREQ_HZ           1000.0f                    // 1kHz（由 TIM6 提供）
#define CONTROL_PERIOD_S          (1.0f / CONTROL_FREQ_HZ)   // 采样周期 0.001s

// ----------------------------------------------------------------------------
// GM6020 电机
// ----------------------------------------------------------------------------
#define MOTOR_ID                  1   // 电机拨码 ID（1~7），反馈帧 0x204 + ID

// CAN 反馈超过该时间未收到，控制器将电流给定置零。
#define CAN_FEEDBACK_TIMEOUT_MS   100
#define CAN_FEEDBACK_TIMEOUT_TICKS \
    ((uint32_t)(CAN_FEEDBACK_TIMEOUT_MS * CONTROL_FREQ_HZ / 1000.0f))

// ----------------------------------------------------------------------------
// 控制模式
//   0 = 速度正弦跟随（单环：速度环）
//   1 = 位置正弦跟随（串级：位置环 -> 速度环）
// ----------------------------------------------------------------------------
#define CONTROL_MODE              1

// ----------------------------------------------------------------------------
// 正弦速度曲线（速度模式）
//   v(t) = SPEED_SINE_AMP_RPM * sin(2*pi*SPEED_SINE_FREQ_HZ*t)  单位 rpm
// ----------------------------------------------------------------------------
#define SPEED_SINE_AMP_RPM        100.0f
#define SPEED_SINE_FREQ_HZ        0.25f

/*// 摩擦前馈：C * tanh(目标转速 / 平滑范围) + B * 目标转速。
// 速度模式和位置模式的速度环共用；参数沿用参考代码，需实机验证。
#define FRICTION_FF_ENABLE               1       // 0 = 关闭前馈
#define FRICTION_FF_COULOMB              400.0f   // 基本摩擦补偿，电流码值，取非负数
#define FRICTION_FF_VISCOUS              1.0f     // 随速度增加的补偿，电流码值/rpm，取非负数
#define FRICTION_FF_SIGN_SCALE_RPM       5.0f     // 零速平滑范围，rpm，须大于 0*/

// ----------------------------------------------------------------------------
// 正弦位置曲线（位置模式，围绕上电位置 home 摆动）
//   p(t) = home + POS_SINE_AMP_DEG * sin(2*pi*POS_SINE_FREQ_HZ*t)  单位 度
// ----------------------------------------------------------------------------
#define POS_SINE_AMP_DEG          180.0f
#define POS_SINE_FREQ_HZ          0.25f

// ----------------------------------------------------------------------------
// 速度环 PID（输入 rpm 误差，输出电流码值，限幅 ±16384）
// ----------------------------------------------------------------------------
#define SPEED_PID_KP              15.0f
#define SPEED_PID_KI              0.2f
#define SPEED_PID_KD              0.0f
#define SPEED_PID_I_MAX           550.0f
#define SPEED_PID_OUT_MAX         16384.0f
#define SPEED_PID_OUT_MIN         (-16384.0f)

// ----------------------------------------------------------------------------
// 位置环 PID（外环，输入角度误差（度），输出速度 rpm，限幅 ±300）
// ----------------------------------------------------------------------------
#define POS_PID_KP                8.0f
#define POS_PID_KI                0.0f
#define POS_PID_KD                0.0f
#define POS_PID_I_MAX             100.0f
#define POS_PID_OUT_MAX           300.0f
#define POS_PID_OUT_MIN           (-300.0f)

#endif // CONFIG_H
